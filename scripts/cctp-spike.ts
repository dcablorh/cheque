async function solanaUsdcBalance(ata: PublicKey): Promise<{ amount: bigint; exists: boolean }> {
  const conn = new Connection(SOLANA_DEVNET_RPC, 'confirmed');
  const info = await conn.getTokenAccountBalance(ata).catch((err: { message?: string }) => {
    if (/could not find account|Invalid param/i.test(String(err?.message ?? err))) {
      return null;
    }
    throw err;
  });
  if (!info) return { amount: 0n, exists: false };
  return { amount: BigInt(info.value.amount), exists: true };
}

