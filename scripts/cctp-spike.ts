async function invoke(signer: Keypair, contractId: string, method: string, args: xdr.ScVal[]): Promise<string> {
  const account = await server.getAccount(signer.publicKey());
  let fee = '100000';
  try {
    const { sorobanInclusionFee } = await server.getFeeStats();
    const p90 = Number(sorobanInclusionFee.p90);
    if (Number.isFinite(p90) && p90 > 0) fee = String(Math.min(p90, 100_000));
  } catch {
    // keep default
  }
  const tx = new TransactionBuilder(account, {
    fee,
    networkPassphrase: NETWORK_PASSPHRASE,
  })
    .addOperation(new Contract(contractId).call(method, ...args))
    .setTimeout(60)
    .build();

  const prepared = await server.prepareTransaction(tx);
  prepared.sign(signer);
  const sent = await server.sendTransaction(prepared);
  if (sent.status === 'ERROR') {
    throw new Error(`Submit failed: ${JSON.stringify(sent.errorResult ?? sent)}`);
  }
  if (sent.status !== 'PENDING' && sent.status !== 'DUPLICATE') {
    throw new Error(`Submit status ${sent.status}: ${JSON.stringify(sent)}`);
  }
  const result = await server.pollTransaction(sent.hash, { attempts: 60 });
  if (result.status !== rpc.Api.GetTransactionStatus.SUCCESS) {
    const detail =
      result.status === rpc.Api.GetTransactionStatus.FAILED
        ? JSON.stringify(result.resultXdr ?? result)
        : result.status;
    throw new Error(`Transaction ${sent.hash} failed: ${detail}`);
  }
  return sent.hash;
}

async function quoteFees(
  destDomain: number,
  extraQuery = '',
): Promise<{ quote: FeeQuote; maxFeeStroops: bigint; forwardFee6: bigint }> {
  const url = `${IRIS_URL}/v2/burn/USDC/fees/${STELLAR_DOMAIN}/${destDomain}?forward=true${extraQuery}`;
  const res = await fetch(url);
  const body = await res.text();
  if (!res.ok) throw new Error(`Fee quote HTTP ${res.status}: ${body}`);
  const quotes = JSON.parse(body) as FeeQuote[];
  const quote = quotes.find((q) => q.finalityThreshold === 2000);
  if (!quote?.forwardFee) throw new Error(`No standard (2000) forward fee quote: ${body}`);
  const forwardFee = quote.forwardFee.high ?? quote.forwardFee.med ?? quote.forwardFee.medium;
  if (forwardFee == null) throw new Error(`forwardFee missing: ${body}`);
  // Use `high` on the spike so destination gas spikes are less likely to stall the forward.
  // Convert 6-decimal forwardFee to Stellar 7-decimal stroops. Do not add a large extra buffer
  // (Circle does not refund unused max_fee from Stellar).
  const protocol = (DEFAULT_BURN_STROOPS * BigInt(Math.ceil(quote.minimumFee * 100))) / 1_000_000n;
  const maxFeeStroops = protocol + BigInt(forwardFee) * 10n;
  return { quote, maxFeeStroops, forwardFee6: BigInt(forwardFee) };
}

function evmAddressToBytes32(address: string): Buffer {
  const hex = address.toLowerCase().replace(/^0x/, '');
  if (!/^[0-9a-f]{40}$/.test(hex)) throw new Error(`Invalid EVM address: ${address}`);
  return Buffer.from(hex.padStart(64, '0'), 'hex');
}

function pubkeyToBytes32(key: PublicKey): Buffer {
  return Buffer.from(key.toBytes());
}

function solanaAtaHook(owner: PublicKey): Buffer {
  const magic = Buffer.alloc(24);
  magic.write('cctp-forward', 'utf-8');
  const version = Buffer.alloc(4); // 0
  const length = Buffer.alloc(4);
  length.writeUInt32BE(33);
  const ataFlag = Buffer.from([1]);
  return Buffer.concat([magic, version, length, ataFlag, Buffer.from(owner.toBytes())]);
}

/**
 * SDK 17.2.1 cannot decode protocol-30 LedgerHeader XDR
 * (`scpValue.ext.v` enum value 3). The JSON-RPC result still includes `sequence`.
 */
async function latestLedgerSequence(): Promise<number> {
  const res = await fetch(SOROBAN_RPC_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'getLatestLedger' }),
  });
  const body = (await res.json()) as { result?: { sequence?: number }; error?: unknown };
  const sequence = body.result?.sequence;
  if (!res.ok || typeof sequence !== 'number') {
    throw new Error(`getLatestLedger failed: ${JSON.stringify(body).slice(0, 300)}`);
  }
  return sequence;
}

