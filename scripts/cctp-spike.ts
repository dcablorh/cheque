async function waitForForward(burnHash: string): Promise<any> {
  const start = Date.now();
  let lastStatus = '';
  while (Date.now() - start < FORWARD_WAIT_MS) {
    const res = await fetch(`${IRIS_URL}/v2/messages/${STELLAR_DOMAIN}?transactionHash=${burnHash}`);
    const body = await res.text();
    if (res.ok) {
      const data = JSON.parse(body) as { messages?: any[] };
      const msg = data.messages?.[0];
      if (msg) {
        const status = `${msg.status ?? ''} / forwardState=${msg.forwardState ?? ''} / forwardTxHash=${msg.forwardTxHash ?? ''}`;
        if (status !== lastStatus) {
          console.log(`  iris: ${status}`);
          lastStatus = status;
        }
        if (msg.forwardTxHash) return msg;
      } else {
        process.stdout.write('.');
      }
    } else if (res.status !== 404) {
      console.log(`  iris HTTP ${res.status}: ${body.slice(0, 200)}`);
    } else {
      process.stdout.write('.');
    }
    await sleep(POLL_MS);
  }
  throw new Error(`Timed out after ${FORWARD_WAIT_MS / 1000}s waiting for forwardTxHash on ${burnHash}`);
}

