function readEnvFile(): string {
  return fs.existsSync(ENV_PATH) ? fs.readFileSync(ENV_PATH, 'utf8') : '';
}

function setEnvVar(key: string, value: string): void {
  let content = readEnvFile();
  const line = `${key}=${value}`;
  const re = new RegExp(`^${key}=.*$`, 'm');
  content = re.test(content) ? content.replace(re, line) : `${content.trimEnd()}\n${line}\n`;
  if (!content.startsWith('#')) {
    content =
      `# Generated by scripts/cctp-spike.ts on ${new Date().toISOString()}\n` +
      `# SECRETS — do not commit this file (.env.local is gitignored).\n` +
      content;
  }
  fs.writeFileSync(ENV_PATH, content.endsWith('\n') ? content : content + '\n', { mode: 0o600 });
  process.env[key] = value;
}

function env(key: string): string | undefined {
  const v = process.env[key];
  return v && v.length > 0 ? v : undefined;
}

async function fundWithFriendbot(publicKey: string, retries = 5): Promise<void> {
  for (let i = 0; i < retries; i++) {
    const res = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(publicKey)}`);
    if (res.ok) return;
    const text = await res.text();
    // Already funded is fine.
    if (res.status === 400 && /already|op_already_exists|createAccount/i.test(text)) return;
    if (i === retries - 1) throw new Error(`Friendbot HTTP ${res.status}: ${text.slice(0, 300)}`);
    await sleep(2000);
  }
}

async function establishTrustline(keypair: Keypair): Promise<void> {
  const account = await horizon.loadAccount(keypair.publicKey());
  const already = account.balances.some(
    (b) => 'asset_code' in b && b.asset_code === USDC_CODE && b.asset_issuer === USDC_ISSUER,
  );
  if (already) return;
  const fee = await horizon.fetchBaseFee();
  const tx = new TransactionBuilder(account, {
    fee: fee.toString(),
    networkPassphrase: NETWORK_PASSPHRASE,
  })
    .addOperation(Operation.changeTrust({ asset: USDC_ASSET }))
    .setTimeout(60)
    .build();
  tx.sign(keypair);
  await horizon.submitTransaction(tx);
}

async function stellarBalances(publicKey: string): Promise<{ xlm: string; usdc: string; usdcTrustline: boolean }> {
  const acc = await horizon.loadAccount(publicKey);
  let xlm = '0';
  let usdc = '0';
  let usdcTrustline = false;
  for (const b of acc.balances) {
    if (b.asset_type === 'native') xlm = b.balance;
    else if ('asset_code' in b && b.asset_code === USDC_CODE && b.asset_issuer === USDC_ISSUER) {
      usdcTrustline = true;
      usdc = b.balance;
    }
  }
  return { xlm, usdc, usdcTrustline };
}

function usdcToStroops(balance: string): bigint {
  const [w, f = ''] = balance.split('.');
  const frac = (f + '0000000').slice(0, 7);
  return BigInt(w + frac);
}

function formatUsdc7(stroops: bigint): string {
  const neg = stroops < 0n;
  const v = neg ? -stroops : stroops;
  const w = v / 10_000_000n;
  const f = (v % 10_000_000n).toString().padStart(7, '0');
  return `${neg ? '-' : ''}${w}.${f}`;
}

function formatUsdc6(units: bigint): string {
  const w = units / 1_000_000n;
  const f = (units % 1_000_000n).toString().padStart(6, '0');
  return `${w}.${f}`;
}

async function ensureStellarRole(prefix: string, needsUsdcTrustline: boolean): Promise<{ publicKey: string }> {
  const existingPub = env(`${prefix}_PUBLIC`);
  const existingSec = env(`${prefix}_SECRET`);
  if (existingPub && existingSec) {
    const kp = Keypair.fromSecret(existingSec);
    if (kp.publicKey() !== existingPub) {
      throw new Error(`${prefix}_PUBLIC does not match ${prefix}_SECRET`);
    }
    await fundWithFriendbot(kp.publicKey());
    if (needsUsdcTrustline) await establishTrustline(kp);
    return { publicKey: kp.publicKey() };
  }
  const kp = Keypair.random();
  console.log(`  Generating ${prefix} ${kp.publicKey()}`);
  await fundWithFriendbot(kp.publicKey());
  if (needsUsdcTrustline) await establishTrustline(kp);
  setEnvVar(`${prefix}_PUBLIC`, kp.publicKey());
  setEnvVar(`${prefix}_SECRET`, kp.secret());
  return { publicKey: kp.publicKey() };
}

function ensureBaseRecipient(): { address: string } {
  const existing = env('BASE_SEPOLIA_RECIPIENT_ADDRESS');
  const existingKey = env('BASE_SEPOLIA_RECIPIENT_PRIVATE_KEY');
  if (existing && existingKey) return { address: existing };
  const privateKey = generatePrivateKey();
  const account = privateKeyToAccount(privateKey);
  setEnvVar('BASE_SEPOLIA_RECIPIENT_ADDRESS', account.address);
  setEnvVar('BASE_SEPOLIA_RECIPIENT_PRIVATE_KEY', privateKey);
  return { address: account.address };
}

