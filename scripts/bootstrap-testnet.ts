import { Keypair, Horizon, Asset, Operation, TransactionBuilder } from '@stellar/stellar-sdk';
import fs from 'node:fs';
import path from 'node:path';

// Circle official testnet USDC details:
// Source documentation URL: https://developers.circle.com/stablecoins/docs/quickstart-transfer-10-usdc-on-chain
// Faucet URL: https://faucet.circle.com/
const USDC_ISSUER = 'GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5';
const USDC_ASSET = new Asset('USDC', USDC_ISSUER);

const HORIZON_URL = 'https://horizon-testnet.stellar.org';
const NETWORK_PASSPHRASE = 'Test SDF Network ; September 2015';
const server = new Horizon.Server(HORIZON_URL);

interface AccountRole {
  role: string;
  envPrefix: string;
  needsUsdcTrustline: boolean;
}

const ROLES: AccountRole[] = [
  { role: 'Contract Admin', envPrefix: 'CONTRACT_ADMIN', needsUsdcTrustline: true },
  { role: 'Claim Authority', envPrefix: 'CLAIM_AUTHORITY', needsUsdcTrustline: false },
  { role: 'Guardian (Multisig)', envPrefix: 'GUARDIAN', needsUsdcTrustline: false },
  { role: 'Funding Account', envPrefix: 'FUNDING_ACCOUNT', needsUsdcTrustline: true },
  { role: 'Settlement Account', envPrefix: 'SETTLEMENT_ACCOUNT', needsUsdcTrustline: true },
  { role: 'Fee-Source Account', envPrefix: 'FEE_SOURCE', needsUsdcTrustline: false },
  { role: 'Channel Account 1', envPrefix: 'CHANNEL_1', needsUsdcTrustline: false },
  { role: 'Channel Account 2', envPrefix: 'CHANNEL_2', needsUsdcTrustline: false },
  { role: 'Channel Account 3', envPrefix: 'CHANNEL_3', needsUsdcTrustline: false },
];

async function fundWithFriendbot(publicKey: string, retries = 3): Promise<void> {
  for (let i = 0; i < retries; i++) {
    try {
      const res = await fetch(`https://friendbot.stellar.org?addr=${encodeURIComponent(publicKey)}`);
      if (res.ok) return;
      const text = await res.text();
      if (i === retries - 1) throw new Error(`Friendbot HTTP ${res.status}: ${text}`);
    } catch (err) {
      if (i === retries - 1) throw err;
      await new Promise((resolve) => setTimeout(resolve, 2000));
    }
  }
}

async function establishTrustline(keypair: Keypair): Promise<void> {
  const account = await server.loadAccount(keypair.publicKey());
  const fee = await server.fetchBaseFee();

  const tx = new TransactionBuilder(account, {
    fee: fee.toString(),
    networkPassphrase: NETWORK_PASSPHRASE,
  })
    .addOperation(
      Operation.changeTrust({
        asset: USDC_ASSET,
      })
    )
    .setTimeout(60)
    .build();

  tx.sign(keypair);
  await server.submitTransaction(tx);
}

async function getBalances(publicKey: string): Promise<{ xlm: string; usdcTrustline: boolean }> {
  try {
    const acc = await server.loadAccount(publicKey);
    let xlm = '0';
    let usdcTrustline = false;
    for (const b of acc.balances) {
      if (b.asset_type === 'native') {
        xlm = b.balance;
      } else if (
        'asset_code' in b &&
        b.asset_code === 'USDC' &&
        b.asset_issuer === USDC_ISSUER
      ) {
        usdcTrustline = true;
      }
    }
    return { xlm, usdcTrustline };
  } catch {
    return { xlm: '0', usdcTrustline: false };
  }
}

async function main() {
  console.log('========================================================================');
  console.log('🚀 DIGITAL CHEQUES FOR GHANA — STELLAR TESTNET BOOTSTRAPPER');
  console.log('========================================================================');
  console.log(`Network: Stellar Testnet (${HORIZON_URL})`);
  console.log(`USDC Issuer: ${USDC_ISSUER} (Circle official testnet)`);
  console.log(`Citation: https://developers.circle.com/stablecoins/docs/quickstart-transfer-10-usdc-on-chain\n`);

  const envLines: string[] = [
    '# Generated by scripts/bootstrap-testnet.ts on ' + new Date().toISOString(),
    'STELLAR_NETWORK=TESTNET',
    `STELLAR_HORIZON_URL=${HORIZON_URL}`,
    'STELLAR_SOROBAN_RPC_URL=https://soroban-testnet.stellar.org',
    `USDC_ISSUER_ADDRESS=${USDC_ISSUER}`,
    'USDC_ASSET_CODE=USDC',
    '',
  ];

  const summaryRows: {
    Role: string;
    'Public Address': string;
    'XLM Balance': string;
    'USDC Trustline': string;
  }[] = [];

  const channelSecrets: string[] = [];

  for (const roleDef of ROLES) {
    process.stdout.write(`⏳ Generating & funding ${roleDef.role}... `);
    const keypair = Keypair.random();
    const pub = keypair.publicKey();
    const sec = keypair.secret();

    await fundWithFriendbot(pub);

    if (roleDef.needsUsdcTrustline) {
      await establishTrustline(keypair);
    }

    const { xlm, usdcTrustline } = await getBalances(pub);

    summaryRows.push({
      Role: roleDef.role,
      'Public Address': pub,
      'XLM Balance': `${parseFloat(xlm).toFixed(2)} XLM`,
      'USDC Trustline': usdcTrustline ? 'ACTIVE ✓' : 'N/A',
    });

    if (roleDef.envPrefix.startsWith('CHANNEL_')) {
      channelSecrets.push(sec);
    } else {
      envLines.push(`${roleDef.envPrefix}_PUBLIC=${pub}`);
      envLines.push(`${roleDef.envPrefix}_SECRET=${sec}`);
    }

    console.log('DONE ✓');
  }

  envLines.push(`CHANNEL_ACCOUNT_SECRETS=${channelSecrets.join(',')}`);

  // Write .env.local safely
  const envLocalPath = path.resolve(process.cwd(), '.env.local');
  fs.writeFileSync(envLocalPath, envLines.join('\n') + '\n', { mode: 0o600 });

  console.log('\n========================================================================');
  console.log('✅ BOOTSTRAP COMPLETE — SUMMARY OF TESTNET ACCOUNTS');
  console.log('========================================================================');
  console.table(summaryRows);
  console.log('========================================================================');
  console.log('🔒 SECURITY NOTICE:');
  console.log('   All generated secret keys were securely saved to: .env.local');
  console.log('   NO SECRETS were echoed to the terminal or logs.');
  console.log('   You can request testnet USDC for the Funding/Settlement accounts at:');
  console.log('   👉 https://faucet.circle.com/');
  console.log('========================================================================\n');
}

main().catch((err) => {
  console.error('Bootstrap failed:', err);
  process.exit(1);
});
